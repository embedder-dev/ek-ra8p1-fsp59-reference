#!/usr/bin/env python3
"""Read-only candidate/source/ELF checks; no IDE, installation or hardware calls.

Usage: python3 tools/ra8p1/verify_candidate.py --manifest REVISION \
  --contract validation/ra8p1/memory-contract.json \
  --project CM85=/absolute/cpu0 --project CM33=/absolute/cpu1

The contract uses the existing memory-contract.json shape: part, fsp, physical
MRAM/SRAM {start,size,ns_start}, cores keyed by configuration.xml Core, with
compiler, debugger, MRAM/SRAM allocations and explicit ITCM/DTCM
{start,size,bus_alias}. TCM aliases are NEVER guessed. Optional aliases arrays
add caller-specified CPU-visible TCM windows; bus_alias and optional bus_aliases
are load/debug destinations only. Both kinds normalize to bus_alias for physical
overlap checks. options entries have address, size and owner, and may supply
physical_start when an alias needs normalization.
No address constants from the hardware are embedded in this verifier.

Optional core fields: elf (project-relative, otherwise Debug/<.project name>.elf),
launch (otherwise the unique project-root .launch), device_command (expected
configuration.xml #DeviceCommand#, defaults to debugger; the launch target is
always checked independently against debugger), condition_facts (PDSC condition
attributes, defaults Dcore derived from compiler and Tcompiler=GCC), and
elf_cpu_name (otherwise compiler, case-insensitive). --elf CORE=RELATIVE overrides
an artifact path. GNU arm-none-eabi-readelf is used via PATH or --readelf.

Each core must supply compile_flags with exact mcpu, mfpu and mfloat-abi values.
Every C/C++/assembly compile_commands.json entry (default Debug/compile_commands.json;
override with compile_commands) is checked without executing its command. Only .ld
records are omitted and explicitly reported as non-compilation records; other
unknown source suffixes fail. The mcpu base must also match compiler; extensions
such as +nopacbti must be explicit. Missing flags/databases and response files fail
closed, except that allow_default_fpu=true permits an omitted -mfpu after probing
the trusted readelf toolchain's sibling GCC driver. The probe preprocesses empty
stdin with recorded target flags and compares __ARM_FP, __ARM_PCS_VFP and
__SOFTFP__ with the same compiler/flags plus the contract's explicit -mfpu. This
establishes FP precision/ABI policy equivalence, not identical optional extensions
(such as MVE) or identical instruction streams. Explicit wrong -mfpu still fails.
Optional elf_attributes requires exact readelf Tag_* values in the linked ELF.
This checks recorded commands and effective compiler defaults, not source-build
binding, database completeness/freshness, or target behavior.

Owning MDFs must exist and exactly match their candidate pack, both at baseline
inspection and when inspecting selected packs. Other baseline/pack differences
are accepted only if both hashes are proven original PDSC-owned bytes from the
pinned FSP 5.9 archive and the pack retains its own
original entry. Changed checkout files must match every candidate owner exactly.
Duplicate component matches are accepted only when their complete parsed XML
serializations are identical, including all attributes, descendants and text.
Distinct selected C/header owners may share a generated path only when every
owner retains its exact pinned original bytes and the existing release-disclaimer
comparison proves the bodies identical. Generated bytes must exactly match one
of those selected owners, not an arbitrary equivalent or unselected original.

Each core must also supply boot with vector_address and vector_alignment. Symbol
names default to __Vectors, __Vectors_End, Reset_Handler, __StackLimit and
__StackTop; override via vector_symbol, vector_end_symbol, reset_symbol,
stack_limit_symbol and stack_top_symbol. stack_alignment defaults to 8. Vectors
and handlers must lie in allocated MRAM/ITCM, stacks in writable SRAM/DTCM.
The complete 0x40-byte fixed table is required, with nonzero Reset, NMI and
HardFault handlers. The full vector extent and every nonzero handler are inspected,
including Thumb state, ELF entry, executable file backing and initial SP/stack bounds.
Synthetic legacy fixtures only may explicitly opt out with a per-core
legacy_fixture object containing skip_compile_commands and/or skip_boot true;
reports label these checks skipped, never verified.

PT_LOAD file bytes at p_paddr and runtime allocations at p_vaddr are both checked
and normalized. p_memsz belongs to the runtime allocation: it is not added to a
separate MRAM load image for initialized RAM. Every nonempty range needs an
explicit allowed window, including TCM and option memory. Zero-file/zero-memory
PT_LOADs are reported as no-ops: size, offset, address and power-of-two alignment
checks still apply, but there are no mapped bytes requiring offset/address
congruence. This is allocation inspection, not general ELF loader qualification.
Physical intersections between different cores fail. This does not bind an ELF to a particular build
invocation, prove installed/support-cache freshness, or establish target behavior.
"""
