def number(value):
    if isinstance(value, bool) or not isinstance(value, (str, int)):
        raise ValueError("Expected an integer address/size")
    try:
        result = int(value, 0) if isinstance(value, str) else value
    except ValueError as error:
        raise ValueError("Invalid integer: " + str(value)) from error
    if result < 0:
        raise ValueError("Negative address/size")
    return result


def interval(start, size, limit):
    start, size = number(start), number(size)
    if start >= limit or size > limit or start + size > limit:
        raise ValueError("Address arithmetic overflow")
    return start, start + size


def windows_for_core(contract, core, *, load=False):
    bits = number(contract.get("address_bits", 32))
    if not 1 <= bits <= 64:
        raise ValueError("Invalid address_bits")
    limit = 1 << bits
    cfg = contract["cores"][core]
    windows = []

    def add(name, start, size, physical):
        begin, end = interval(start, size, limit)
        canonical, _ = interval(physical, size, limit)
        if begin != end:
            item = (begin, end, canonical, name)
            if item not in windows:
                windows.append(item)

    for name in ("MRAM", "SRAM"):
        physical = contract["physical"][name]
        base, end = interval(physical["start"], physical["size"], limit)
        allocated = cfg[name]
        start, stop = interval(allocated["start"], allocated["size"], limit)
        if not base <= start <= stop <= end:
            raise ValueError(core + " allocation outside physical " + name)
        add(name, start, stop - start, start)
        if "ns_start" in physical:
            interval(physical["ns_start"], physical["size"], limit)
            add(name, number(physical["ns_start"]) + start - base, stop - start, start)
    for name in ("ITCM", "DTCM"):
        region = cfg[name]  # Both windows must be explicitly supplied, even if size zero.
        physical = region["bus_alias"]
        starts = [region["start"], *region.get("aliases", [])]
        if load:
            starts += [physical, *region.get("bus_aliases", [])]
        for start in starts:
            add(name, start, region["size"], physical)
    for name, region in contract.get("options", {}).items():
        if region["owner"] not in contract["cores"]:
            raise ValueError("Unknown option-memory owner: " + region["owner"])
        if region["owner"] == core:
            add(name, region["address"], region["size"], region.get("physical_start", region["address"]))
    for left, (a, b, canonical, _) in enumerate(windows):
        for c, d, other, _ in windows[left + 1:]:
            if max(a, c) < min(b, d) and canonical - a != other - c:
                raise ValueError("Ambiguous address windows for " + core)
    return windows, limit


def normalize(start, size, windows, limit):
    begin, end = interval(start, size, limit)
    if begin == end:
        return None
    matches = {(physical + begin - a, physical + end - a)
               for a, b, physical, _ in windows if a <= begin and end <= b}
    if len(matches) != 1:
        raise ValueError("Range outside explicit allowed windows: " + hex(begin) + ".." + hex(end))
    return next(iter(matches))


def parse_readelf(text):
    fields = {}
    for line in text.splitlines():
        match = re.match(r"\s*(Class|Data|Machine|Entry point address|Tag_[A-Za-z0-9_]+):\s*(.*?)\s*$", line)
        if match:
            key, value = match.groups()
            if key in fields and fields[key] != value:
                raise ValueError("Conflicting ELF identity fields")
            fields[key] = value.strip('"')
    segments = []
    for line in text.splitlines():
        if not re.match(r"\s*LOAD(?:\s|$)", line):
            continue
        match = LOAD.fullmatch(line)
        if not match:
            raise ValueError("Malformed PT_LOAD line: " + line)
        offset, virtual, physical, filesz, memsz, flags, alignment = match.groups()
        segments.append({"offset": int(offset, 16), "virtual": int(virtual, 16),
                         "physical": int(physical, 16), "filesz": int(filesz, 16),
                         "memsz": int(memsz, 16), "flags": flags.replace(" ", ""),
                         "alignment": int(alignment, 16)})
    if not segments:
        raise ValueError("ELF has no PT_LOAD segments")
    return fields, segments


def elf_ranges(text, file_size, contract, core):
    fields, segments = parse_readelf(text)
    cfg = contract["cores"][core]
    if fields.get("Class") != "ELF32" or fields.get("Machine") != "ARM":
        raise ValueError("Wrong ELF architecture for " + core)
    expected = cfg.get("elf_cpu_name", cfg["compiler"])
    if fields.get("Tag_CPU_name", "").casefold() != expected.casefold():
        raise ValueError("Wrong ELF CPU for " + core + ": " + fields.get("Tag_CPU_name", "missing"))
    attributes = cfg.get("elf_attributes", {})
    if not isinstance(attributes, dict) or any(not isinstance(name, str) or not isinstance(value, str)
                                               for name, value in attributes.items()):
        raise ValueError("elf_attributes must map readelf Tag_* names to strings")
    for name, value in attributes.items():
        if not re.fullmatch(r"Tag_[A-Za-z0-9_]+", name) or fields.get(name) != value:
            raise ValueError("Wrong/missing ELF attribute " + name + " for " + core + ": " + fields.get(name, "missing"))
    runtime_windows, limit = windows_for_core(contract, core)
    load_windows, _ = windows_for_core(contract, core, load=True)
    ranges = set()
    for segment in segments:
        if segment["filesz"] > segment["memsz"]:
            raise ValueError("PT_LOAD file size exceeds memory size")
        _, file_end = interval(segment["offset"], segment["filesz"], limit)
        if file_end > file_size:
            raise ValueError("PT_LOAD extends beyond ELF file")
        alignment = segment["alignment"]
        # GNU ld retains unused explicit PHDRS with no bytes and an arbitrary
        # in-file offset. Only a nonempty mapping needs address/offset congruence.
        if alignment > 1 and (alignment & (alignment - 1) or
                              (segment["memsz"] and segment["virtual"] % alignment != segment["offset"] % alignment)):
            raise ValueError("Invalid PT_LOAD alignment")
        for start, size, windows in ((segment["physical"], segment["filesz"], load_windows),
                                     (segment["virtual"], segment["memsz"], runtime_windows)):
            result = normalize(start, size, windows, limit)
            if result is not None:
                ranges.add(result)
    if not ranges:
        raise ValueError("ELF has no nonempty allocated ranges")
    return sorted(ranges)


def disjoint(project_ranges):
    items = list(project_ranges.items())
    for index, (left, ranges) in enumerate(items):
        for right, others in items[index + 1:]:
            for a, b in ranges:
                for c, d in others:
                    if max(a, c) < min(b, d):
                        raise ValueError("Physical overlap between " + left + " and " + right
                                         + ": " + hex(max(a, c)) + ".." + hex(min(b, d)))


def owning_source(entry):
    if entry.startswith(".module_descriptions/"):
        return entry[1:]
    relative = project_source(entry)
    return relative if relative and relative.startswith(("ra/fsp/", "ra/board/")) else None


def check_owning_mdfs(source_root, entries):
    checked = set()
    for entry, expected in entries.items():
        if not entry.startswith(".module_descriptions/"):
            continue
        relative = owning_source(entry)
        source = safe_path(source_root, relative)
        if not source.is_file() or digest(source.read_bytes()) != expected:
            raise ValueError("Missing/stale owning baseline MDF: " + relative)
        checked.add(relative)
    return checked


def original_source_hashes():
    """Original per-owner bytes, established only through the pinned release loader."""
    with ExitStack() as stack:
        packs = pack_builder.load_release(ROOT / "reference/vendor/FSP_Packs_v5.9.0.zip", stack)
        result = {}
        for name, pack in packs.items():
            for entry in pack_builder.inspect_pack(pack):
                relative = owning_source(entry)
                if relative is not None:
                    result.setdefault(relative, {})[(name, entry)] = digest(pack.original(entry))
    return result


def check_baseline(source_root, manifest, contents):
    checked, accepted = set(), {}
    originals = None
    for name, files in contents.items():
        checked.update(check_owning_mdfs(source_root, manifest["packs"][name]["entries"]))
        for entry in files:
            relative = owning_source(entry)
            if relative is None or entry.startswith(".module_descriptions/"):
                continue
            path = safe_path(source_root, relative)
            if path.exists():
                if not path.is_file():
                    raise ValueError("Stale baseline-to-pack source: " + name + ":" + entry)
                current = digest(path.read_bytes())
                expected = manifest["packs"][name]["entries"][entry]
                if current != expected:
                    if originals is None:
                        originals = original_source_hashes()
                    variants = originals.get(relative, {})
                    # Both sides must be exact originals of this source, and the
                    # candidate must retain this particular owner's original bytes.
                    if current not in variants.values() or variants.get((name, entry)) != expected:
                        raise ValueError("Stale baseline-to-pack source: " + name + ":" + entry)
                    accepted[(name, entry)] = current
                checked.add(relative)
    if not checked:
        raise ValueError("No owning baseline source inventory")
    return checked, accepted


def condition_matches(identifier, pdsc, facts, visiting=()):
    if not identifier:
        return True
    if identifier in visiting:
        raise ValueError("Cyclic PDSC condition: " + identifier)
    matches = [node for node in pdsc.findall("./conditions/condition") if node.get("id") == identifier]
    if len(matches) != 1:
        raise ValueError("Unknown/ambiguous PDSC condition: " + identifier)
    results = {"require": [], "accept": [], "deny": []}
    for node in matches[0]:
        if node.tag not in results:
            raise ValueError("Unsupported PDSC condition clause: " + node.tag)
        terms = []
        for key, value in node.attrib.items():
            if key == "condition":
                terms.append(condition_matches(value, pdsc, facts, (*visiting, identifier)))
            elif key in facts:
                terms.append(facts[key] == value)
            else:
                raise ValueError("Missing PDSC condition fact: " + key)
        results[node.tag].append(all(terms))
    return (all(results["require"]) and (not results["accept"] or any(results["accept"]))
            and not any(results["deny"]))


def check_project_sources(project, source_root, manifest, contents, facts, original_variants):
    configuration = xml(safe_path(project, "configuration.xml").read_bytes())
    expected, owners = {}, set()
    for selection in configuration.findall("./raComponentSelection/component"):
        name = selection.findtext("originalPack")
        if name not in contents:
            continue  # Unchanged stock packs are outside this candidate manifest.
        files = contents[name]
        descriptors = [entry for entry in files if entry.endswith(".pdsc")]
        if len(descriptors) != 1:
            raise ValueError("Expected one PDSC: " + name)
        pdsc = xml(files[descriptors[0]])
        components = {ET.tostring(node) for node in pdsc.findall("./components/component") if all(
            node.get(pack, "") == selection.get(config, "") for config, pack in ATTRIBUTES)}
        # Some release PDSCs repeat complete records. Collapse only exact XML
        # serializations, never identities or source lists with differing metadata.
        if len(components) != 1:
            raise ValueError("Selected component is not unique: " + name)
        component = xml(components.pop())
        if not condition_matches(component.get("condition"), pdsc, facts):
            raise ValueError("Selected component fails its PDSC condition: " + name)
        owners.add(name)
        # MDFs are pack support resources, not generated project-source records.
        check_owning_mdfs(source_root, manifest["packs"][name]["entries"])
        for item in component.findall("./files/file"):
            entry = item.get("name", "")
            if not entry or entry.endswith("/") or item.get("attr") == "template":
                continue
            if not condition_matches(item.get("condition"), pdsc, facts):
                continue
            relative = project_source(entry)
            if relative is None:
                continue
            if entry not in files:
                raise ValueError("Missing PDSC source: " + entry)
            value = manifest["packs"][name]["entries"][entry]
            expected.setdefault(relative, {})[(name, entry)] = value
            owned = owning_source(entry)
            if owned and Path(owned).suffix in (".c", ".h"):
                source = safe_path(source_root, owned)
                if not source.is_file():
                    raise ValueError("Missing/stale owning baseline source: " + owned)
                current = digest(source.read_bytes())
                if current != value and original_variants.get((name, entry)) != current:
                    raise ValueError("Missing/stale owning baseline source: " + owned)
    if not owners or not expected:
        raise ValueError("No selected candidate source inventory")
    originals, reconciled = None, []
    for relative, records in expected.items():
        hashes = set(records.values())
        if len(hashes) > 1:
            if originals is None:
                originals = original_source_hashes()
            variants = originals.get(relative, {})
            # Every selected owner must retain its own pinned original bytes,
            # and only the release's exact disclaimer banners may differ.
            if (owning_source(relative) != relative or Path(relative).suffix not in (".c", ".h") or
                    any(variants.get(owner) != value for owner, value in records.items()) or
                    not pack_builder.disclaimer_equivalent([contents[name][entry] for name, entry in records])):
                raise ValueError("Conflicting selected source owners: " + relative)
        path = safe_path(project, relative)
        if not path.is_file():
            raise ValueError("Missing/stale generated project source: " + relative)
        current = digest(path.read_bytes())
        if current not in hashes:
            raise ValueError("Missing/stale generated project source: " + relative)
        if len(hashes) > 1:
            reconciled.append({"path": relative, "generated_sha256": current,
                               "owners": [{"pack": name, "entry": entry, "sha256": value}
                                          for (name, entry), value in sorted(records.items())]})
    return {"checked_sources": len(expected), "packs": sorted(owners),
            "reconciled_original_source_owners": sorted(reconciled, key=lambda record: record["path"])}


def project_identity(project, contract, core):
    cfg = contract["cores"][core]
    root = xml(safe_path(project, "configuration.xml").read_bytes())
    settings = root.findall("./generalSettings/option")
    expected = {"Core": core, "#TargetName#": contract["part"], "#FSPVersion#": contract["fsp"],
                "#TargetARCHITECTURE#": cfg["compiler"], "#DeviceCommand#": cfg.get("device_command", cfg["debugger"])}
    for key, value in expected.items():
        if [n.get("value") for n in settings if n.get("key") == key] != [value]:
            raise ValueError("Wrong project identity for " + core + ": " + key)
    if cfg.get("launch"):
        launches = [safe_path(project, cfg["launch"])]
    else:
        launches = list(Path(project).glob("*.launch"))
    if len(launches) != 1:
        raise ValueError("Specify the unique launch path in the core contract: " + core)
    launch = xml(safe_path(project, launches[0].relative_to(project).as_posix()).read_bytes())
    parameters = [n.get("value", "") for n in launch.findall("./stringAttribute")
                  if n.get("key") == "com.renesas.cdt.core.serverParam"]
    if len(parameters) != 1:
        raise ValueError("Missing/ambiguous launch server parameters")
    tokens = shlex.split(parameters[0])
    devices = [tokens[i + 1] for i, token in enumerate(tokens[:-1]) if token == "-t"]
    if devices != [cfg["debugger"]]:
        raise ValueError("Wrong launch debugger core: " + core)
    return cfg


def fixture_skip(cfg, check):
    legacy = cfg.get("legacy_fixture", {})
    if not isinstance(legacy, dict) or any(type(value) is not bool for value in legacy.values()):
        raise ValueError("legacy_fixture must contain explicit boolean opt-outs")
    return legacy.get("skip_" + check, False)


def probe_fp_macros(compiler, target_flags):
    result = subprocess.run([str(compiler), *target_flags, "-dM", "-E", "-x", "c", "-"],
                            input="", capture_output=True, text=True, timeout=30,
                            env={**os.environ, "LC_ALL": "C"})
    if result.returncode or result.stderr.strip():
        raise ValueError("Compiler FP probe failed: " + (result.stderr.strip() or str(result.returncode)))
    macros = {name: 0 for name in ("__ARM_FP", "__ARM_PCS_VFP", "__SOFTFP__")}
    for line in result.stdout.splitlines():
        match = re.fullmatch(r"#define (\w+) (\S+)", line)
        if match and match[1] in macros:
            macros[match[1]] = number(match[2])
    if not macros["__ARM_FP"]:
        raise ValueError("Compiler FP probe did not establish hardware FP support")
    return macros


def check_default_fpu(compiler, target_flags, expected_fpu):
    observed = probe_fp_macros(compiler, target_flags)
    reference = probe_fp_macros(compiler, [*target_flags, "-mfpu=" + expected_fpu])
    if observed != reference:
        raise ValueError("Compiler default FPU/ABI mismatch: " + repr(observed) + " != " + repr(reference))
    return {"policy": "effective compiler default", "compiler": str(compiler),
            "target_flags": target_flags, "reference_mfpu": expected_fpu,
            "observed_macros": observed, "reference_macros": reference}


def check_compile_commands(project, cfg, compiler=None):
    if fixture_skip(cfg, "compile_commands"):
        return {"status": "skipped: explicit legacy fixture opt-out"}
    path = safe_path(project, cfg.get("compile_commands", "Debug/compile_commands.json"))
    if not path.is_file():
        raise ValueError("Missing compile_commands.json: " + str(path))
    expected = cfg.get("compile_flags")
    names = ("mcpu", "mfpu", "mfloat-abi")
    if (not isinstance(expected, dict) or set(expected) != set(names) or
            any(not isinstance(expected[name], str) or not expected[name] for name in names)):
        raise ValueError("Core contract requires compile_flags: mcpu, mfpu, mfloat-abi")
    if expected["mcpu"].split("+", 1)[0] != cfg["compiler"]:
        raise ValueError("Contract compile_flags mcpu disagrees with compiler")
    raw = path.read_bytes()
    entries = json.loads(raw)
    if not isinstance(entries, list) or not entries:
        raise ValueError("compile_commands.json must be a nonempty array")
    default_fpu = cfg.get("allow_default_fpu", False)
    if type(default_fpu) is not bool:
        raise ValueError("allow_default_fpu requires an explicit boolean")
    checked, omitted, probes = [], [], {}
    for index, entry in enumerate(entries):
        label = "compile_commands.json entry " + str(index)
        if (not isinstance(entry, dict) or
                any(not isinstance(entry.get(key), str) or not entry[key] for key in ("directory", "file"))):
            raise ValueError("Malformed " + label)
        suffix = Path(entry["file"]).suffix
        arguments = entry.get("arguments")
        if arguments is not None and (not isinstance(arguments, list) or not arguments or
                                      any(not isinstance(token, str) for token in arguments)):
            raise ValueError("Malformed arguments in " + label)
        if "command" in entry:
            if not isinstance(entry["command"], str):
                raise ValueError("Malformed command in " + label)
            command = shlex.split(entry["command"])
            if arguments is not None and arguments != command:
                raise ValueError("Conflicting command/arguments in " + label)
            arguments = command
        if suffix == ".ld" and arguments and "-c" not in arguments and not any(token.startswith("-x") for token in arguments):
            omitted.append({"file": entry["file"], "reason": "non-compilation linker-script record (.ld)"})
            continue
        if suffix not in (".c", ".C", ".cc", ".cp", ".cpp", ".cxx", ".c++", ".s", ".S", ".sx", ".asm"):
            raise ValueError("Unsupported compilation source suffix in " + label + ": " + suffix)
        if not arguments or not re.fullmatch(r"arm-none-eabi-(?:gcc|g\+\+)(?:-[0-9.]+)?", Path(arguments[0]).name):
            raise ValueError("Wrong compiler executable in " + label)
        found = {name: [] for name in names}
        machine_flags = []
        tokens = iter(arguments[1:])
        for token in tokens:
            if (token.startswith("@") or token in ("-marm", "-mno-thumb", "-msoft-float", "-mhard-float",
                                                    "-mgeneral-regs-only", "-Xassembler", "-Xclang", "--") or
                    token.startswith(("-march", "-Wa,", "-specs", "--specs")) or token in (";", "&&", "||", "|")):
                raise ValueError("Unsupported target override/indirection in " + label + ": " + token)
            for name in names:
                flag = "-" + name
                if token == flag:
                    value = next(tokens, "")
                    found[name].append(value)
                    machine_flags.append(flag + "=" + value)
                    break
                if token.startswith(flag + "="):
                    found[name].append(token[len(flag) + 1:])
                    machine_flags.append(token)
                    break
            else:
                if token.startswith("-m"):
                    machine_flags.append(token)
        implicit = default_fpu and not found["mfpu"]
        for name in names:
            if name == "mfpu" and implicit:
                continue
            if not found[name] or any(value != expected[name] for value in found[name]):
                raise ValueError("Wrong/missing compiler -" + name + " in " + label + " (" + entry["file"] +
                                 "): expected " + expected[name] + ", got " + repr(found[name]))
        item = {"file": entry["file"], "compiler": arguments[0],
                "flags": {name: found[name][-1] if found[name] else None for name in names}}
        if implicit:
            if not compiler:
                raise ValueError("Default FPU checking requires a trusted toolchain compiler")
            trusted = Path(shutil.which(str(compiler)) or compiler).resolve()
            # C++ records use the same trusted toolchain's C++ driver, not an arbitrary DB executable.
            if "g++" in Path(arguments[0]).name:
                trusted = trusted.with_name(trusted.name.replace("gcc", "g++"))
            recorded = Path(arguments[0])
            if not recorded.is_absolute():
                recorded = Path(entry["directory"]) / recorded if recorded.parent != Path(".") else Path(shutil.which(str(recorded)) or recorded)
            if recorded.resolve() != trusted.resolve():
                raise ValueError("Default FPU compiler differs from trusted toolchain in " + label)
            key = (str(trusted), *machine_flags, expected["mfpu"])
            if key not in probes:
                probes[key] = check_default_fpu(trusted, machine_flags, expected["mfpu"])
            item["effective_fpu"] = probes[key]
        checked.append(item)
    if not checked:
        raise ValueError("compile_commands.json contains no C/C++/assembly compilation records")
    return {"status": "checked", "path": str(path), "sha256": digest(raw),
            "checked_entries": len(checked), "entries": checked, "omitted_noncompilation_entries": omitted}


def elf_symbols(text, names):
    symbols = {}
    for line in text.splitlines():
        match = re.fullmatch(r"\s*\d+:\s+([0-9a-fA-F]+)\s+\d+\s+\S+\s+\S+\s+\S+\s+(\S+)\s+(\S+)\s*", line)
        if not match:
            continue
        value, section, name = match.groups()
        if section == "UND" or name not in names:
            continue
        value = int(value, 16)
        if name in symbols and symbols[name] != value:
            raise ValueError("Conflicting ELF symbol: " + name)
        symbols[name] = value
    return symbols


def check_boot(data, text, contract, core):
    cfg = contract["cores"][core]
    if fixture_skip(cfg, "boot"):
        return {"status": "skipped: explicit legacy fixture opt-out"}
    boot = cfg.get("boot")
    if not isinstance(boot, dict) or not {"vector_address", "vector_alignment"} <= boot.keys():
        raise ValueError("Core contract requires boot: vector_address, vector_alignment")
    fields, segments = parse_readelf(text)
    if fields.get("Class") != "ELF32" or fields.get("Machine") != "ARM" or "little endian" not in fields.get("Data", ""):
        raise ValueError("Boot inspection requires little-endian ARM ELF32")
    symbol_names = {key: boot.get(key + "_symbol", default) for key, default in (
        ("vector", "__Vectors"), ("vector_end", "__Vectors_End"), ("reset", "Reset_Handler"),
        ("stack_limit", "__StackLimit"), ("stack_top", "__StackTop"))}
    if any(not isinstance(name, str) or not name for name in symbol_names.values()):
        raise ValueError("Invalid boot symbol name")
    symbols = elf_symbols(text, set(symbol_names.values()))

    def symbol(key):
        name = symbol_names[key]
        if name not in symbols:
            raise ValueError("Missing boot ELF symbol: " + name)
        return symbols[name]

    vector = symbol("vector")
    vector_end = symbol("vector_end")
    reset = symbol("reset")
    stack_limit = symbol("stack_limit")
    stack_top = symbol("stack_top")
    windows, limit = windows_for_core(contract, core)

    def in_regions(start, size, regions, label):
        try:
            return normalize(start, size, [item for item in windows if item[3] in regions], limit)
        except ValueError as error:
            raise ValueError(label + " outside allocated " + "/".join(regions) + ": " + str(error)) from error

    def aligned(value, alignment, label):
        alignment = number(alignment)
        if not alignment or alignment & (alignment - 1) or value % alignment:
            raise ValueError("Invalid " + label + " alignment")

    def backed(start, size, flag, label, file_backed=True):
        # A single unambiguous segment must cover the entire requested extent.
        candidates = [segment for segment in segments if flag in segment["flags"] and
                      segment["virtual"] <= start and start + size <= segment["virtual"] +
                      segment["filesz" if file_backed else "memsz"]]
        if len(candidates) != 1:
            raise ValueError(label + " lacks unique " + flag + " PT_LOAD backing")
        offset = candidates[0]["offset"] + start - candidates[0]["virtual"]
        if file_backed and offset + size > len(data):
            raise ValueError(label + " extends beyond ELF file")
        return offset

    if vector != number(boot["vector_address"]):
        raise ValueError("Wrong vector table address")
    aligned(vector, boot["vector_alignment"], "vector")
    # HM 14.3.1 Table 14.3: fixed exceptions occupy offsets 0x00 through 0x3c.
    if vector_end - vector < 0x40 or (vector_end - vector) % 4:
        raise ValueError("Invalid vector table extent")
    in_regions(vector, vector_end - vector, ("MRAM", "ITCM"), "Vector table")
    offset = backed(vector, vector_end - vector, "R", "Vector table")
    initial_sp, reset_vector = struct.unpack_from("<II", data, offset)
    if not reset_vector & 1 or reset_vector != (reset | 1):
        raise ValueError("Wrong reset vector/Thumb state")
    if number(fields.get("Entry point address", "missing")) != reset_vector:
        raise ValueError("ELF entry does not match reset vector")
    handlers = 0
    for index, (handler,) in enumerate(struct.iter_unpack("<I", data[offset + 4:offset + vector_end - vector]), 1):
        if handler == 0:
            if index in (1, 2, 3):  # Reset, NMI and HardFault are mandatory.
                raise ValueError("Missing mandatory vector handler at offset " + hex(index * 4))
            continue  # Reserved, security-dependent and unpopulated interrupt slots.
        if not handler & 1:
            raise ValueError("Vector handler lacks Thumb state")
        address = handler & ~1
        in_regions(address, 2, ("MRAM", "ITCM"), "Vector handler")
        backed(address, 2, "E", "Vector handler")
        handlers += 1
    if stack_top <= stack_limit or initial_sp != stack_top:
        raise ValueError("Wrong initial stack pointer/stack bounds")
    for value in (stack_limit, stack_top):
        aligned(value, boot.get("stack_alignment", 8), "stack")
    in_regions(stack_limit, stack_top - stack_limit, ("SRAM", "DTCM"), "Stack")
    backed(stack_limit, stack_top - stack_limit, "W", "Stack", file_backed=False)
    return {"status": "checked", "vector_address": hex(vector), "vector_end": hex(vector_end),
            "reset": hex(reset_vector), "entry": fields["Entry point address"], "initial_sp": hex(initial_sp),
            "stack_limit": hex(stack_limit), "stack_top": hex(stack_top), "checked_handlers": handlers}


def inspect_elf(path, readelf):
    result = subprocess.run([str(readelf), "-W", "-h", "-l", "-A", "-s", str(path)],
                            capture_output=True, text=True, timeout=30,
                            env={**os.environ, "LC_ALL": "C"})
    if result.returncode or result.stderr.strip():
        raise ValueError("readelf failed: " + (result.stderr.strip() or str(result.returncode)))
    return result.stdout


def verify(manifest_path, contract, projects, source_root, readelf, elves=None):
    _, manifest, contents = read_manifest(manifest_path)
    checked, original_variants = check_baseline(source_root, manifest, contents)
    if not projects or set(projects) - contract["cores"].keys():
        raise ValueError("No projects or unknown contract core")
    if len({Path(path).resolve() for path in projects.values()}) != len(projects):
        raise ValueError("Project paths must be distinct")
    if elves and set(elves) - projects.keys():
        raise ValueError("ELF override without a project")
    report, physical = {}, {}
    for core, directory in projects.items():
        project = Path(directory).absolute()
        cfg = project_identity(project, contract, core)
        compiler_path = Path(shutil.which(str(readelf)) or readelf).resolve().with_name("arm-none-eabi-gcc")
        compiler = check_compile_commands(project, cfg, compiler=compiler_path)
        facts = {"Tcompiler": "GCC", "Dcore": cfg["compiler"].replace("cortex-m", "Cortex-M"),
                 **cfg.get("condition_facts", {})}
        sources = check_project_sources(project, source_root, manifest, contents, facts, original_variants)
        relative = (elves or {}).get(core, cfg.get("elf"))
        if not relative:
            name = xml(safe_path(project, ".project").read_bytes()).findtext("name")
            if not name:
                raise ValueError("Missing project name for ELF selection")
            relative = "Debug/" + name + ".elf"
        artifact = safe_path(project, relative)
        if not artifact.is_file():
            raise ValueError("Missing ELF: " + str(artifact))
        data = artifact.read_bytes()
        text = inspect_elf(artifact, readelf)
        physical[core] = elf_ranges(text, len(data), contract, core)
        boot = check_boot(data, text, contract, core)
        fields, segments = parse_readelf(text)
        report[core] = {**sources, "elf": str(artifact), "elf_sha256": digest(data),
                        "compile_commands": compiler, "boot": boot, "elf_identity": fields,
                        "ignored_empty_load_segments": [{"index": index, **segment} for index, segment in enumerate(segments)
                                                        if segment["filesz"] == segment["memsz"] == 0],
                        "physical_ranges": [[hex(a), hex(b)] for a, b in physical[core]]}
    disjoint(physical)
    return {"success": True, "manifest_packs": len(contents), "baseline_sources": len(checked),
             "baseline_original_variants": [{"pack": name, "entry": entry, "checkout_sha256": current,
                                             "pack_entry_sha256": manifest["packs"][name]["entries"][entry]}
                                            for (name, entry), current in sorted(original_variants.items())],
             "projects": report, "physical_disjoint": True,

            "scope": "File/source identity, recorded compile flags and ELF boot/allocation; not build execution or hardware verification"}


def assignments(values):
    result = {}
    for value in values:
        key, separator, path = value.partition("=")
        if not key or not separator or not path or key in result:
            raise ValueError("Expected unique CORE=PATH: " + value)
        result[key] = path
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--contract", type=Path, required=True)
    parser.add_argument("--project", action="append", required=True, metavar="CORE=PATH")
    parser.add_argument("--elf", action="append", default=[], metavar="CORE=RELATIVE_PATH")
    parser.add_argument("--source-root", type=Path, default=ROOT / "baseline")
    parser.add_argument("--readelf", default=shutil.which("arm-none-eabi-readelf"))
    args = parser.parse_args(argv)
    try:
        if not args.readelf:
            raise ValueError("arm-none-eabi-readelf unavailable; supply --readelf")
        contract = json.loads(args.contract.read_text())
        report = verify(args.manifest, contract, assignments(args.project), args.source_root,
                        args.readelf, assignments(args.elf))
    except (ValueError, KeyError, TypeError, OSError, ET.ParseError, zipfile.BadZipFile,
            subprocess.SubprocessError) as error:
        parser.exit(1, "Candidate verification failed: " + str(error) + "\n")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
